    private void jTablePacienteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTablePacienteMouseClicked
        if (jTablePaciente.getSelectedRow() != -1) {
            jTextFieldNome.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 1).toString());
            jFormattedTextFieldCpf.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 2).toString());
            jTextFieldEndereco.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 3).toString());
            jFormattedTextFieldTelefone.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 4).toString());
            jFormattedTextFieldNascimento.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 5).toString());
            jTextFieldEspecialidade.setText(jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 6).toString());
        }

    }//GEN-LAST:event_jTablePacienteMouseClicked

    private void jButtonAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAtualizarActionPerformed
        if (jTablePaciente.getSelectedRow() != -1) {
            if (pacienteController.update((int) jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 0),
                    jTextFieldNome.getText(),
                    jFormattedTextFieldCpf.getText(),
                    jTextFieldEndereco.getText(),
                    jFormattedTextFieldTelefone.getText(),
                    jFormattedTextFieldNascimento.getText(),
                    jTextFieldEspecialidade.getText()
            )) {
                this.getListaPaciente();
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Paciente atualizado com sucesso!");
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possivel atualizar o paciente!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonAtualizarActionPerformed

