    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
        if (jTablePaciente.getSelectedRow() != -1) {
            if (pacienteController.delete((int) jTablePaciente.getValueAt(jTablePaciente.getSelectedRow(), 0))) {
                this.getListaPaciente();
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Paciente excluido com sucesso!");
            } else {
                JOptionPane.showConfirmDialog(this, "Não foi possivel excluir o paciente", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonExcluirActionPerformed

    private void jButtonAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAdicionarActionPerformed

        String cpf = jFormattedTextFieldCpf.getText().replace(".", "").replace("-", "").replace(" ", "");
        String telefone = jFormattedTextFieldTelefone.getText().replace("(", "").replace(")", "").replace("-", "").replace(" ", "");
        String nascimento = jFormattedTextFieldNascimento.getText().replace("/", "").replace(" ", "");

        if (jTextFieldNome.getText().equals("") || jTextFieldEndereco.getText().equals("") || jTextFieldEspecialidade.getText().equals("") || cpf.equals("") || telefone.equals("") || nascimento.equals("")) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos.", "Atenção", JOptionPane.WARNING_MESSAGE);
        } else {

            if (pacienteController.create(jTextFieldNome.getText(), jFormattedTextFieldCpf.getText(), jTextFieldEndereco.getText(), jFormattedTextFieldTelefone.getText(), jFormattedTextFieldNascimento.getText(), jTextFieldEspecialidade.getText())) {
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Paciente salvo com sucesso!");
                this.getListaPaciente();
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possivel salvar o paciente!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonAdicionarActionPerformed

