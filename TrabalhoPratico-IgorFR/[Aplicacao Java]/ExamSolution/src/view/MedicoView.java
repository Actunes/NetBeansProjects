    private void getListaMedico() {
        modeloTabelaMedico = (DefaultTableModel) jTableMedico.getModel();
        modeloTabelaMedico.setNumRows(0);

        for (Medico m : medicoController.read()) {
            modeloTabelaMedico.addRow(new Object[]{
                m.getId_medico(),
                m.getNome(),
                m.getCpf(),
                m.getEndereco(),
                m.getTelefone(),
                m.getCrm(),
                m.getEspecialidade()
            });
        }
    }

