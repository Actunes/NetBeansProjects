    private void jButtonAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAdicionarActionPerformed

        String cpf = jFormattedTextFieldCpf.getText().replace(".", "").replace("-", "").replace(" ", "");
        String telefone = jFormattedTextFieldTelefone.getText().replace("(", "").replace(")", "").replace("-", "").replace(" ", "");

        if (jTextFieldNome.getText().equals("") || jTextFieldEndereco.getText().equals("") || jTextFieldEspecialidade.getText().equals("") || cpf.equals("") || telefone.equals("") || jTextFieldCrm.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos.", "Atenção", JOptionPane.WARNING_MESSAGE);
        } else {

            if (medicoController.create(jTextFieldNome.getText(), jFormattedTextFieldCpf.getText(), jTextFieldEndereco.getText(), jFormattedTextFieldTelefone.getText(), jTextFieldCrm.getText(), jTextFieldEspecialidade.getText())) {
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Medico salvo com sucesso!");
                this.getListaMedico();
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possivel salvar o Medico!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonAdicionarActionPerformed

    private void jButtonAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAtualizarActionPerformed
        if (jTableMedico.getSelectedRow() != -1) {
            if (medicoController.update((int) jTableMedico.getValueAt(jTableMedico.getSelectedRow(), 0),
                    jTextFieldNome.getText(),
                    jFormattedTextFieldCpf.getText(),
                    jTextFieldEndereco.getText(),
                    jFormattedTextFieldTelefone.getText(),
                    jTextFieldCrm.getText(),
                    jTextFieldEspecialidade.getText()
            )) {
                this.getListaMedico();
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Medico atualizado com sucesso!");
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possivel atualizar o medico!", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonAtualizarActionPerformed

    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
        if (jTableMedico.getSelectedRow() != -1) {
            if (medicoController.delete((int) jTableMedico.getValueAt(jTableMedico.getSelectedRow(), 0))) {
                this.getListaMedico();
                limpaCampos();
                JOptionPane.showMessageDialog(this, "Medico excluido com sucesso!");
            } else {
                JOptionPane.showConfirmDialog(this, "Não foi possivel excluir o medico", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonExcluirActionPerformed

