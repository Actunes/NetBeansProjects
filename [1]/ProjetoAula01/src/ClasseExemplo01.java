public class ClasseExemplo01 {
    public static void main(String[] args){
        int x=5, y=2, k;
        System.out.println("x = " + x);
        System.out.println("y = " + y);
        System.out.println("-x = " + (-x));
        System.out.println("x + y = " + (x+y));
        System.out.println("x - y = " + (x-y));
        System.out.println("x * y = " + (x*y));
        System.out.println("x / y = " + (x/y));
        System.out.println("x / y = " + (float) x/y);
        System.out.println("x % y = " + (x%y));
        System.out.println("x++ = " + (x++));
        System.out.println("++x = " + (++x));
        System.out.println("y-- = " + (y--));
        System.out.println("--y = " + (--y));
    }
    
    
}
